"""Compare Phase 2-4 outputs before and after the official-clock correction.

Usage:  python3 audit/compare_with_baseline.py [BASELINE_ROOT]
BASELINE_ROOT defaults to .baseline_pre_clockfix/ (a local snapshot of the repository before the correction; it can be
regenerated by running the Phase 2-4 scripts with REFIT_OFFICIAL_CLOCK=as_published in a copy of the repository).
Writes outputs/tables/audit/06_baseline_vs_corrected_files.csv and 07_baseline_vs_corrected_metrics.csv.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
BASE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / ".baseline_pre_clockfix"
OUT = ROOT / "outputs/tables/audit"


def file_status() -> pd.DataFrame:
    rows = []
    for sub in ("tables/phase2", "tables/phase3", "tables/phase4", "figures/phase2", "figures/phase3", "figures/phase4", "models/phase3"):
        for f in sorted((ROOT / "outputs" / sub).glob("*")):
            b = BASE / "outputs" / sub / f.name
            if not b.exists():
                rows.append({"File": f"outputs/{sub}/{f.name}", "Status": "new"})
                continue
            same = hashlib.md5(f.read_bytes()).hexdigest() == hashlib.md5(b.read_bytes()).hexdigest()
            if not same and f.suffix == ".csv":
                x, y = pd.read_csv(b), pd.read_csv(f)
                same = x.equals(y)
            rows.append({"File": f"outputs/{sub}/{f.name}", "Status": "unchanged" if same else "changed"})
    return pd.DataFrame(rows)


def kv(path: Path) -> pd.Series:
    return pd.read_csv(path).set_index("metric")["value"]


def metrics() -> pd.DataFrame:
    rows = []

    def add(phase, metric, old, new):
        rows.append({"Phase": phase, "Metric": metric, "Before": old, "After": new,
                     "Change": (new - old) if isinstance(old, (int, float, np.number)) and isinstance(new, (int, float, np.number)) else np.nan})

    for phase, rel in ((2, "tables/phase2/12_key_numbers.csv"), (3, "tables/phase3/17_key_numbers.csv")):
        a, b = kv(BASE / "outputs" / rel), kv(ROOT / "outputs" / rel)
        for m in a.index.union(b.index):
            add(phase, m, a.get(m, np.nan), b.get(m, np.nan))
    # Phase 2 per-house cycle summary and peak hours
    for col in ("likely_cycles", "complete_cycles", "cycles_per_week", "duration_min_median", "energy_kwh_median"):
        a = pd.read_csv(BASE / "outputs/tables/phase2/06_cycle_summary_by_house.csv").set_index("house")
        b = pd.read_csv(ROOT / "outputs/tables/phase2/06_cycle_summary_by_house.csv").set_index("house")
        if col in a and col in b:
            for h in a.index:
                add(2, f"{col}__house_{h}", a.loc[h, col], b.loc[h, col])
    # Phase 4 pooled and per-house exposure, model comparison, heating, resolution, sample size
    e_a = pd.read_csv(BASE / "outputs/tables/phase4/02_peak_window_exposure.csv").set_index("house")
    e_b = pd.read_csv(ROOT / "outputs/tables/phase4/02_peak_window_exposure.csv").set_index("house")
    for col in ("weekday_likely_cycles", "weekday_cycles_starting_in_window", "pct_weekday_starts_in_window",
                "pct_weekday_wm_energy_in_window", "mean_wm_w_in_window", "annual_wm_kwh_in_window_est",
                "mean_aggregate_kw_in_window", "wm_share_of_window_aggregate_pct", "median_frac_energy_inside_window_for_window_starts"):
        for h in e_a.index:
            add(4, f"exposure__{col}__{h}", e_a.loc[h, col], e_b.loc[h, col])
    c_a = pd.read_csv(BASE / "outputs/tables/phase4/05_model_vs_actual_window_starts.csv")
    c_b = pd.read_csv(ROOT / "outputs/tables/phase4/05_model_vs_actual_window_starts.csv")
    for df in (c_a, c_b):
        df["key"] = df["criterion"] + " | " + df["setting"] + " | " + df["house"].astype(str)
    c_a, c_b = c_a.set_index("key"), c_b.set_index("key")
    for k in c_a.index[c_a.index.str.endswith("pooled")]:
        for col in ("actual_window_starts", "actual_weekday_cycles", "pred_window_starts", "pred_pct_window_starts",
                    "actual_pct_window_starts", "actual_window_starts_matched", "pred_window_starts_matched",
                    "window_recall", "window_precision", "mean_abs_house_error_pct_points"):
            add(4, f"model_window__{col}__{k}", c_a.loc[k, col], c_b.loc[k, col])
    h_a = pd.read_csv(BASE / "outputs/tables/phase4/04_heating_energy_share.csv").set_index("house")
    h_b = pd.read_csv(ROOT / "outputs/tables/phase4/04_heating_energy_share.csv").set_index("house")
    for h in h_a.index:
        add(4, f"heating_share_pct__{h}", h_a.loc[h, "pct_wm_energy_while_heating"], h_b.loc[h, "pct_wm_energy_while_heating"])
    r_a = pd.read_csv(BASE / "outputs/tables/phase4/06_resolution_visibility.csv")
    r_b = pd.read_csv(ROOT / "outputs/tables/phase4/06_resolution_visibility.csv")
    for df in (r_a, r_b):
        df.index = df["house"].astype(str) + "@" + df["resolution_min"].astype(str) + "min"
    for k in r_a.index[r_a.index.str.startswith("pooled")]:
        for col in ("median_visibility_ratio", "pct_cycles_ratio_ge_2"):
            add(4, f"resolution__{col}__{k}", r_a.loc[k, col], r_b.loc[k, col])
    s_a = pd.read_csv(BASE / "outputs/tables/phase4/08_illustrative_sample_size.csv")
    s_b = pd.read_csv(ROOT / "outputs/tables/phase4/08_illustrative_sample_size.csv")
    for i in range(len(s_a)):
        add(4, f"sample_size__households_per_arm__{s_a.loc[i, 'assumed_reduction_share_of_wm_window_power']}",
            s_a.loc[i, "households_per_arm"], s_b.loc[i, "households_per_arm"])
    add(4, "sample_size__sigma_kw", s_a.loc[0, "sigma_between_household_kw"], s_b.loc[0, "sigma_between_household_kw"])
    return pd.DataFrame(rows)


if __name__ == "__main__":
    if not BASE.exists():
        sys.exit(f"Baseline not found: {BASE}")
    OUT.mkdir(parents=True, exist_ok=True)
    f, m = file_status(), metrics()
    f.to_csv(OUT / "06_baseline_vs_corrected_files.csv", index=False)
    m.to_csv(OUT / "07_baseline_vs_corrected_metrics.csv", index=False)
    print(f.Status.value_counts().to_string())
    print(f[f.Status != "changed"].to_string(index=False))
    pd.set_option("display.width", 220)
    pd.set_option("display.max_rows", 400)
    mm = m[(m.Before != m.After) & ~(m.Before.isna() & m.After.isna())]
    print(mm.to_string(index=False))
